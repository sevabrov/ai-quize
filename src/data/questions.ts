/**
 * Контент квізу — єдине джерело правди для питань та реакцій AI-помічника.
 * Тексти взяті з ТЗ без скорочень.
 *
 * `id` питання + `id` варіанта утворюють ключ сигналу для scoring-engine
 * (напр. питання 4, варіант c -> "4c"). Див. src/lib/scoring.ts.
 */

export type QuestionKind = 'text' | 'single'

export interface QuizOption {
  /** Літера варіанта у ТЗ, вона ж частина ключа сигналу: 2c, 4a, 9e … */
  id: string
  /** Емодзі з ТЗ — рендериться окремим чипом, а не всередині тексту */
  emoji?: string
  label: string
  /** Для довгих варіантів (питання 15) */
  bullets?: string[]
  /** Реакція робота саме на цей варіант */
  reaction: string
}

export interface Question {
  id: number
  /** Коротка назва для чеклиста «Твій прогрес» */
  step: string
  title: string
  hint?: string
  kind: QuestionKind
  placeholder?: string
  options?: QuizOption[]
  /** Універсальна реакція (для текстового питання або коли ТЗ дає одну реакцію) */
  reaction?: string
}

